#!/usr/bin/env bash
# Copy the design tokens into the default page: public/tokens.css is the CSS file of the @meddleware/design-tokens release pinned in
# scripts/design-tokens.version, with a header saying so. The page's style.css uses only that file's roles, so it follows the tokens
# (light/dark, 7:1 text contrast) without carrying a colour of its own.
#
#   scripts/sync-tokens.sh           write public/tokens.css
#   scripts/sync-tokens.sh --check   fail if public/tokens.css differs from the pinned release (CI runs this)
#
# TOKENS_TARBALL=/path/to/meddleware-design-tokens-X.Y.Z.tgz uses a local pack instead of the registry (to try a token change before release).
set -euo pipefail
cd "$(dirname "$0")/.."

version=$(tr -d '[:space:]' < scripts/design-tokens.version)
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

if [ -n "${TOKENS_TARBALL:-}" ]; then
  tarball=$TOKENS_TARBALL
else
  (cd "$work" && npm pack "@meddleware/design-tokens@${version}" --silent >/dev/null)
  tarball=$(ls "$work"/*.tgz)
fi
tar -xzf "$tarball" -C "$work" package/src/tokens.css

{
  echo "/* Generated by scripts/sync-tokens.sh from @meddleware/design-tokens ${version}. Do not edit: change the tokens, then run the script. */"
  cat "$work/package/src/tokens.css"
} > "$work/tokens.css"

if [ "${1:-}" = "--check" ]; then
  if ! diff -u public/tokens.css "$work/tokens.css" >/dev/null; then
    echo "public/tokens.css differs from @meddleware/design-tokens ${version}: run scripts/sync-tokens.sh" >&2
    exit 1
  fi
  echo "public/tokens.css matches @meddleware/design-tokens ${version}"
else
  cp "$work/tokens.css" public/tokens.css
  echo "public/tokens.css written from @meddleware/design-tokens ${version}"
fi
